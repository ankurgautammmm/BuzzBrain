/**
 * Helper to get available streams for a class
 */
export function getStreamsForClass(classGrade: string): StreamNode[] {
  const node = CURRICULUM_STRUCTURE[classGrade as keyof typeof CURRICULUM_STRUCTURE];
  return node?.streams || [];
}

/**
 * Helper to get available subjects for a class and optional stream
 */
export function getSubjectsForClass(classGrade: string, stream?: string): string[] {
  const node = CURRICULUM_STRUCTURE[classGrade as keyof typeof CURRICULUM_STRUCTURE];
  if (!node) return [];

  if (node.hasStreams) {
    if (stream) {
      const found = node.streams?.find((s) => s.name.toLowerCase() === stream.toLowerCase());
      return found ? found.subjects : [];
    }
    // Return all unique subjects across streams
    const all = new Set<string>();
    node.streams?.forEach((s) => s.subjects.forEach((sub) => all.add(sub)));
    return Array.from(all);
  }

  return node.subjects || [];
}

/**
 * Helper to filter chapters by class, stream, subject, and search query
 */
export function filterCurriculumChapters(options: {
  classGrade?: string;
  stream?: string;
  subject?: string;
  searchQuery?: string;
}): CurriculumChapter[] {
  const { classGrade, stream, subject, searchQuery } = options;
  const q = (searchQuery || '').trim().toLowerCase();

  return ALL_CURRICULUM_CHAPTERS.filter((ch) => {
    if (classGrade && ch.classGrade !== classGrade) return false;
    if (stream && ch.stream && ch.stream.toLowerCase() !== stream.toLowerCase()) return false;
    if (subject && subject !== 'All' && ch.subject.toLowerCase() !== subject.toLowerCase()) return false;

    if (!q) return true;

    const fullText = [
      ch.title,
      ch.subject,
      ch.unit,
      ch.stream || '',
      ...ch.keyTopics,
      ch.predictivePatternNote,
    ].join(' ').toLowerCase();

    return fullText.includes(q);
  });
}

export const CURRICULUM_CHAPTERS = ALL_CURRICULUM_CHAPTERS;

export function searchCurriculum(query: string, classGrade?: string): CurriculumChapter[] {
  return filterCurriculumChapters({ searchQuery: query, classGrade });
}
